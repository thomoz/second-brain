"""Markdown report for the Volume-Spike + Record-Earnings Scan -- a single
candidates-pending-review.md, mirroring goat.dma_breakout_scan.render_dma_breakout_
candidates_report's shape (no per-row score, just the signal(s) that fired), the
closest precedent for a binary signal-trip scan in this codebase.

Overwritten every run, advisor notes only. A `"BOTH SIGNALS — "` detail prefix for
signal_type == "both" rows is already baked into signal_detail by scan.py
(Decision #2) -- this module just renders it.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

from . import config

_SYDNEY_TZ = ZoneInfo("Australia/Sydney")


def _now_sydney_str() -> str:
    return datetime.now(_SYDNEY_TZ).strftime("%Y-%m-%d %H:%M %Z")


_DISCLAIMER = (
    "Auto-generated by the Volume-Spike + Record-Earnings daily scan -- overwritten "
    "every run. Advisor notes only; no trade action is ever suggested here (see "
    "SOUL.md). Run your own my-trader `find` / briefs-finance `assess` on anything "
    "you like."
)


def render_candidates_report(result: dict[str, Any]) -> str:
    lines = [
        "# Volume-Spike + Record-Earnings Candidates — Pending Review",
        "",
        "What this is: US small/micro-cap ($50M-$2B) names that either had today's "
        "trading volume spike far above their recent average, or just reported a "
        "record (or sharply accelerating) earnings quarter -- two independent "
        "'Wall St is about to notice this' signals. Either alone stages a "
        "candidate; a ticker firing BOTH in the same run is marked accordingly so "
        "you can see the strongest case at a glance. 'Record' means record within "
        "the free yfinance reporting window available (~5-6 quarters), not a true "
        "all-time record. Review each one and either `promote-candidate` (writes "
        "it into my-trader's real watchlist) or `dismiss-candidate` (discards it). "
        "Edits here are overwritten on the next `scan` run.",
        "",
        _DISCLAIMER,
        "",
        f"Scanned {result['scanned']} ticker(s), slice "
        f"{result['slice_index'] + 1}/{result['slices']} of the screened universe "
        f"({result['screened_total']} screened total).",
        "",
    ]
    if result.get("finviz_failed"):
        lines.append(
            "> Finviz screen fetch failed this run and no universe cache exists yet -- "
            "scan ran against zero names."
        )
        lines.append("")

    lines += [
        "| Ticker | Company | Signal | Detail | Flagged |",
        "|--------|---------|--------|--------|---------|",
    ]
    pending = sorted(
        result.get("pending_candidates", []),
        key=lambda r: r.get("flagged_at", ""),
        reverse=True,
    )
    for row in pending:
        company = (row.get("company_name") or "n/a").replace("|", "/")
        detail = (row.get("signal_detail") or "").replace("|", "/")
        lines.append(
            f"| {row['ticker']} | {company} | {row['signal_type']} | {detail} "
            f"| {str(row.get('flagged_at', ''))[:10]} |"
        )
    if not pending:
        lines.append("| _(none)_ | | | | |")

    lines += ["", f"Last auto-generated: {_now_sydney_str()}."]
    return "\n".join(lines) + "\n"


def write_candidates_report(result: dict[str, Any]) -> None:
    config.VE_CANDIDATES_MD_PATH.write_text(
        render_candidates_report(result), encoding="utf-8"
    )
